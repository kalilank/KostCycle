// Node-only. Regenerates two paste-in files for the Supabase SQL Editor:
//   supabase/all_migrations_for_new_project.sql  (every migration, in order)
//   supabase/seed_demo.sql                       (optional demo catalog, no service-role key)
// Run: npm run build:sql
import { readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { demoListings, demoSellers, seedNamespace } from "./demo-data.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const migrationsDir = join(root, "supabase", "migrations");

export async function migrationFiles() {
  return (await readdir(migrationsDir))
    .filter((f) => /^\d{12}_.+\.sql$/.test(f))
    .sort();
}

export async function buildAllMigrations() {
  const files = await migrationFiles();
  const parts = [
    "-- KostCycle: ALL migrations in order, for a NEW, EMPTY Supabase project.",
    "-- Generated by `npm run build:sql`. Do not edit by hand.",
    "-- Paste into Supabase > SQL Editor > New query and press Run ONCE.",
    "-- Never run this on a project that already has the KostCycle tables.",
    `-- Contains: ${files.join(", ")}`,
    "",
  ];
  for (const file of files) {
    const sql = (await readFile(join(migrationsDir, file), "utf8")).replace(
      /\r\n/g,
      "\n",
    );
    parts.push(
      `-- ===========================================================================`,
      `-- ${file}`,
      `-- ===========================================================================`,
      sql.trimEnd(),
      "",
    );
  }
  return parts.join("\n") + "\n";
}

const lit = (value) =>
  value === null || value === undefined
    ? "null"
    : typeof value === "number"
      ? String(value)
      : `'${String(value).replace(/'/g, "''")}'`;
const textArray = (values) => `array[${values.map(lit).join(",")}]::text[]`;
// Deterministic ids so reruns are idempotent: md5(text) is a valid uuid.
const sellerId = (seller) =>
  `md5(${lit(`${seedNamespace}:${seller.email}`)})::uuid`;

export function buildSeedSql() {
  const users = demoSellers.map((s) => {
    const app = JSON.stringify({
      provider: "email",
      providers: ["email"],
      seed_namespace: seedNamespace,
    });
    const meta = JSON.stringify({
      name: s.name,
      residence: s.residence,
      university: "BINUS University",
      campus: "Alam Sutera",
    });
    return `  ('00000000-0000-0000-0000-000000000000', ${sellerId(s)}, 'authenticated', 'authenticated', ${lit(s.email)}, '', now(), ${lit(app)}::jsonb, ${lit(meta)}::jsonb, now(), now(), '', '', '', '', now() + interval '100 years')`;
  });
  const listings = demoListings.map((l) => {
    const seller = demoSellers[l.sellerIndex];
    return `  (${sellerId(seller)}, ${lit(l.name)}, ${lit(l.category)}, ${lit(l.condition)}, ${l.price}, ${lit(l.university)}, ${lit(l.campus)}, ${lit(l.residence)}, ${l.distance}, ${textArray(l.pickup)}, ${lit(l.description)}, ${l.image_index}, true, ${lit(l.seed_key)})`;
  });
  return `-- KostCycle OPTIONAL demo catalog: ${demoSellers.length} synthetic sellers, ${demoListings.length} browse-only listings.
-- Generated by \`npm run build:sql\` from scripts/demo-data.mjs. Do not edit by hand.
-- Run in Supabase > SQL Editor AFTER all_migrations_for_new_project.sql.
-- No service-role key needed: the SQL Editor already runs as the project owner.
-- Safe to rerun: fixed ids and seed keys, ON CONFLICT DO NOTHING, nothing is deleted.
-- The sellers are banned accounts with no password and .invalid emails: nobody
-- can sign in as them, and the database blocks reservations of demo items.
begin;

-- Abort if a non-demo account already uses one of these emails.
do $$
begin
  if exists (
    select 1 from auth.users
    where email like ${lit(`${seedNamespace}-%@example.invalid`)}
      and coalesce(raw_app_meta_data->>'seed_namespace', '') <> ${lit(seedNamespace)}
  ) then
    raise exception 'Seed email collision with a real account; nothing was changed.';
  end if;
end;
$$;

insert into auth.users (instance_id, id, aud, role, email, encrypted_password,
  email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
  confirmation_token, email_change, email_change_token_new, recovery_token, banned_until)
values
${users.join(",\n")}
on conflict (id) do nothing;

-- The signup trigger created their profiles; mark them as demo.
update public.profiles set is_demo = true
where id in (${demoSellers.map(sellerId).join(", ")});

insert into public.listings (seller_id, name, category, condition, price, university,
  campus, residence, distance, pickup, description, image_index, is_demo, seed_key)
values
${listings.join(",\n")}
on conflict (seed_key) do nothing;

commit;

select (select count(*) from public.profiles where is_demo) as demo_sellers,
       (select count(*) from public.listings where is_demo) as demo_listings;
`;
}

async function main() {
  await writeFile(
    join(root, "supabase", "all_migrations_for_new_project.sql"),
    await buildAllMigrations(),
  );
  await writeFile(join(root, "supabase", "seed_demo.sql"), buildSeedSql());
  console.log(
    "Wrote supabase/all_migrations_for_new_project.sql and supabase/seed_demo.sql",
  );
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1])
  main().catch((e) => {
    console.error(e.message);
    process.exitCode = 1;
  });
